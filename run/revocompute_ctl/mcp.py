"""Deployment control for the opt-in agent MCP surface: route, health, rollback.

One switch — ``MCP_ENABLED`` in the deployment env file — decides the whole
opt-in, so "is MCP deployed?" cannot be answered two different ways:

``MCP_ENABLED`` unset or false
    No gateway route is written and the Compose overlay is not layered, so
    ``/k/`` is not a route at all and the web service never sees the switch.
    The deployment serves the HTTP API and the Web application exactly as
    before.  This is the default.

``MCP_ENABLED=true``
    The Compose overlay adds the ``mcp`` service (the existing
    ``revocompute-mcp`` entrypoint, ``python -m revocompute.mcp``) and the
    gateway gains exactly one location, ``/k/`` -> that service's
    container-internal port.  The service is a *separate process* from the
    Gunicorn web service on purpose: the web service runs ``--preload`` and forks
    workers, so a listener started at import time would live in the master,
    unsupervised, and be re-forked on every worker recycle.  There is still no
    published port and no second execution plane: the ``mcp`` process imports the
    canonical application, so the canonical authorization, admission, and result
    rules are the ones that apply, and the canonical Redis limiter and the
    SQLite stores both processes read under the shared server directory (user,
    Task, admin config, Tool call, MCP handle, and Operator Job records) are the
    durable truth it shares.  What is *not* shared is the limiter's in-memory
    fallback, which is per process by construction and used only while Redis is
    unavailable, and the Operator Job restart pass, a startup action the web
    service owns alone.

The gateway reads its configuration only at container start, so a change is
served after the gateway is restarted; :func:`apply_gateway` reports whether the
route state actually changed so the caller restarts it only then.
"""

from __future__ import annotations

import json
import os
import sys
import urllib.error
import urllib.request

from revocompute_ctl.compose import container_fs, mcp_enabled

#: Server-owned constants.  The upstream is the *service* name and its
#: container-internal port on the compose network, never a host port: nothing
#: outside the stack can reach the listener even while the route exists.  The
#: name matches the ``mcp`` service ``docker-compose.mcp.yml`` declares, which is
#: what ``compose up`` starts once the overlay is layered.
GATEWAY_SNIPPET = "mcp-gateway/mcp.conf"
MCP_PATH = "/k"
#: The streamable-HTTP endpoint under the prefix, and the protocol revision the
#: readiness handshake asks to negotiate.  These describe the wire an MCP client
#: speaks, which is a protocol fact rather than a scientific or Runner fact.
MCP_ENDPOINT = f"{MCP_PATH}/mcp"
MCP_PROTOCOL_VERSION = "2025-06-18"
MCP_UPSTREAM_PORT = 8081
#: The compose service the gateway proxies ``/k/`` to.  ``docker-compose.mcp.yml``
#: declares exactly this name; the web process reads it from ``MCP_SERVICE`` for
#: the readiness fact, and this controller writes the same host into the route.
UPSTREAM_SERVICE = "mcp"


def gateway_snippet_path(state) -> str:
    return os.path.join(state.server_dir(), *GATEWAY_SNIPPET.split("/"))


def _upstream_port(state) -> int:
    """The container-internal port of the ``mcp`` service.

    ``MCP_PORT`` comes from the deployment env file (Compose interpolates it into
    the ``mcp`` service, and the web process reads the same value for its
    readiness fact), so the controller reads the value the service binds rather
    than the controller's own process environment.
    """
    raw = (state.get("MCP_PORT") or "").strip()
    if not raw:
        return MCP_UPSTREAM_PORT
    try:
        return int(raw)
    except ValueError:
        print(f"MCP_PORT must be an integer, got {raw!r}.", file=sys.stderr)
        raise SystemExit(1) from None


def _snippet(*, port: int) -> str:
    # Exactly one location.  The trailing slash makes it a prefix, so only
    # /k/* is proxied and no MCP path can address an operator or admin surface.
    # The proxy settings match the API location's, so the streaming transport
    # gets the same buffering and timeout behavior as the rest of the API rather
    # than a second, invented policy.
    return (
        "# Generated by restart.sh from MCP_ENABLED. Do not edit by hand.\n"
        "# Route ownership is deployment-owned; the nginx template includes this mask.\n"
        f"location {MCP_PATH}/ {{\n"
        f"    proxy_pass http://{UPSTREAM_SERVICE}:{port};\n"
        "    proxy_http_version 1.1;\n"
        '    proxy_set_header Connection "";\n'
        "    proxy_set_header Host $host;\n"
        "    proxy_set_header X-Real-IP $remote_addr;\n"
        "    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n"
        "    proxy_set_header X-Forwarded-Proto $origin_proto;\n"
        "}\n"
    )


def _current_snippet(state) -> str | None:
    """The route text already on disk, or ``None`` when it cannot be read.

    An unreadable file is treated as "changed": the write below runs as the
    runner identity, so it can still reconcile a file the invoking host user
    cannot open, and the walk is better off restarting the gateway once than
    leaving two sources of truth.
    """
    try:
        with open(gateway_snippet_path(state), encoding="utf-8") as handle:
            return handle.read()
    except OSError:
        return None


def apply_gateway(state, *, dry_run: bool = False) -> bool:
    """Reconcile the gateway route with ``MCP_ENABLED``; True when it changed."""
    path = gateway_snippet_path(state)
    if not mcp_enabled(state):
        if not os.path.isfile(path):
            return False
        if dry_run:
            print(f"MCP gateway route would be removed: {path}")
            return False
        # SERVER_DIR is the runner identity's directory, so removal goes through
        # the same throwaway-container path the write uses rather than assuming
        # the invoking host user can unlink it.
        container_fs(state, f"rm -f /srv/{GATEWAY_SNIPPET}", [(state.server_dir(), "/srv")])
        print(f"MCP gateway route removed: {path}")
        return True
    port = _upstream_port(state)
    snippet = _snippet(port=port)
    if _current_snippet(state) == snippet:
        # The route already says exactly this.  Rewriting it would be a no-op that
        # still reported a change, and the caller restarts the gateway only when the
        # route state actually changed — so an unchanged route must say so.
        return False
    if dry_run:
        print(f"MCP gateway route would be written: {path} ({MCP_PATH}/ -> {UPSTREAM_SERVICE}:{port})")
        return False
    # The route text carries nginx variables ($host, $remote_addr), so it travels as
    # an argument and is written with a quoted ``printf '%s'`` rather than through a
    # here-doc or stdin, which would expand it. mkdir and the write happen in one
    # program because the mask directory may not exist on a first opt-in.
    container_fs(
        state,
        f"mkdir -p /srv/{os.path.dirname(GATEWAY_SNIPPET)} && printf '%s' \"$0\" > /srv/{GATEWAY_SNIPPET}",
        [(state.server_dir(), "/srv")],
        args=[snippet],
    )
    print(f"MCP gateway route written: {path} ({MCP_PATH}/ -> {UPSTREAM_SERVICE}:{port})")
    return True


def mcp_health(state) -> int:
    """Prove the MCP surface really answers, over the route a client uses.

    "The switch is set" is not "the surface works": the ``mcp`` service may not be
    running, the port can be held, or the gateway can be serving a stale config
    with no ``/k/`` route at all.  The operator is the one side that can see the
    whole chain, so this walks it: the web process reports each fact it observed
    (whether the ``mcp`` service answered, the gateway route state the web process
    reads, and the public endpoint it reached), and this then drives its *own* MCP
    ``initialize`` over the public route a client uses -- the same handshake an
    agent host performs first.  A deployment that never opted in reports the
    surface absent (exit 0); an opt-in deployment whose endpoint does not answer,
    or whose web process reports the surface non-operational while the env file
    says it should be on, is a real operator problem and is reported as failure --
    never silently as "disabled".  The probe is unauthenticated on purpose:
    ``initialize`` is the pre-credential handshake, so it proves the surface
    exists without carrying, printing, or storing any credential.  Whether a
    request may *do* anything is still decided per request by the canonical
    account and admission rules.
    """
    base = (state.get("SERVER_BASE_URL") or "").rstrip("/")
    if not base:
        print("SERVER_BASE_URL is not set; cannot probe the MCP capability.", file=sys.stderr)
        return 1
    url = f"{base}/compute/api/mcp"
    try:
        with urllib.request.urlopen(url, timeout=10) as response:  # noqa: S310 - operator-configured URL
            payload = json.loads(response.read().decode("utf-8"))
    except (urllib.error.URLError, OSError, ValueError) as exc:
        print(f"The web service did not answer the MCP capability probe at {url}: {exc}", file=sys.stderr)
        return 1
    opted_in = mcp_enabled(state)
    if not payload.get("enabled"):
        if opted_in:
            _report_not_operational(state, payload)
            return 1
        print("MCP surface disabled on this deployment.")
        return 0
    # The capability is operational: the deployment's own public endpoint answered
    # a genuine MCP handshake.  The operator confirms it from this side too, over
    # the public route an agent host will use, so the receipt is not one process
    # agreeing with itself.
    ok, detail = _initialize_handshake(base)
    if not ok:
        print(f"MCP is enabled but the endpoint did not answer an MCP handshake: {detail}", file=sys.stderr)
        return 1
    print(f"MCP surface reachable at {base}{MCP_ENDPOINT} ({detail}).")
    print(f"MCP service internal port {_upstream_port(state)} (never published).")
    print("Rollback: set MCP_ENABLED=false in the deployment env file, then run `bash run/restart.sh restart`.")
    return 0


def _report_not_operational(state, payload: dict) -> None:
    """Name the operator's next action from the facts the web process reported.

    The capability carries the deployment's own observed facts and a fixed,
    role-based reason; the specifics an operator needs to act on — the route file
    this host would have written, its on-disk presence, the internal port — are
    printed here, from this host's own state, and never travel through the API.
    """
    route = gateway_snippet_path(state)
    present = os.path.isfile(route)
    reason = payload.get("detail") or "the running web process reports the MCP service not answering"
    print(f"MCP_ENABLED is set in the env file but the surface is not operational: {reason}", file=sys.stderr)
    print(
        f"  service answering:   {payload.get('listener_ready')}\n"
        f"  gateway route state: {payload.get('route_configured')} ({'present' if present else 'absent'} at {route})\n"
        f"  public endpoint reached: {payload.get('gateway_verified')}",
        file=sys.stderr,
    )
    if payload.get("listener_ready") is not True:
        print(
            "The `mcp` service is not answering; check that the overlay is layered and the service is running "
            "(`docker compose ps`), then run `bash run/restart.sh restart`.",
            file=sys.stderr,
        )
    elif payload.get("route_configured") is not True or not present:
        print("Write the gateway route with `bash run/restart.sh restart`.", file=sys.stderr)
    else:
        print(
            "The route exists; the gateway must be reloaded and the endpoint reachable from this host "
            "(set MCP_GATEWAY_PROBE=true in the deployment env file to have the web process verify it).",
            file=sys.stderr,
        )


def _initialize_handshake(base: str) -> tuple[bool, str]:
    """Drive one MCP ``initialize`` over streamable HTTP; ``(ok, detail)``.

    Returns the negotiated protocol version and server name on success.  A 4xx
    with a response means the *route* is reachable but the surface refused (a
    proxy that stops it, a wrong path) — a real failure the operator must see,
    distinguished in the message from "nothing answered at all".
    """
    body = json.dumps(
        {
            "jsonrpc": "2.0",
            "id": 1,
            "method": "initialize",
            "params": {
                "protocolVersion": MCP_PROTOCOL_VERSION,
                "capabilities": {},
                "clientInfo": {"name": "revocompute-mcp-status", "version": "1"},
            },
        }
    ).encode("utf-8")
    request = urllib.request.Request(  # noqa: S310 - operator-configured URL
        f"{base}{MCP_ENDPOINT}",
        data=body,
        headers={"Content-Type": "application/json", "Accept": "application/json, text/event-stream"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=10) as response:  # noqa: S310 - operator-configured URL
            payload = _decode_jsonrpc(response.headers.get("Content-Type", ""), response.read())
        status = response.status
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", "replace")[:200]
        return False, f"the route answered HTTP {exc.code}: {detail}"
    except (urllib.error.URLError, OSError, ValueError) as exc:
        return False, f"nothing answered a decodable MCP response at the route: {exc}"
    if status != 200:
        return False, f"the route answered HTTP {status}"
    result = payload.get("result") if isinstance(payload, dict) else None
    if not isinstance(result, dict) or "protocolVersion" not in result:
        return False, f"the response was not an MCP initialize result: {str(payload)[:200]}"
    server = result.get("serverInfo") or {}
    return True, f"protocol {result['protocolVersion']}, server {server.get('name', 'unknown')}"


def _decode_jsonrpc(content_type: str, raw: bytes) -> object:
    """Decode a streamable-HTTP MCP response body.

    The transport answers ``initialize`` as a single ``text/event-stream`` frame
    (``data: {...}``); an implementation that negotiates JSON answers with the
    object directly.  Both are accepted, because the check is "did the server
    answer MCP", not "which framing did it choose".
    """
    text = raw.decode("utf-8", "replace").strip()
    if "text/event-stream" in content_type.lower():
        for line in text.splitlines():
            if line.startswith("data:"):
                text = line[len("data:") :].strip()
                break
    return json.loads(text)


def cmd_mcp_status(state) -> int:
    """``mcp-status``: the switch, the route, and what the process reports."""
    path = gateway_snippet_path(state)
    print(f"MCP_ENABLED: {'true' if mcp_enabled(state) else 'false'}")
    print(f"Gateway route: {path} ({'present' if os.path.isfile(path) else 'absent'})")
    print(f"MCP service internal port: {_upstream_port(state)} (never published)")
    return mcp_health(state)


