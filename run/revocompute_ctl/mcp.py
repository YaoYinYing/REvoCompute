"""Deployment control for the opt-in agent MCP surface: route, health, rollback.

One switch — ``MCP_ENABLED`` in the deployment env file — decides the whole
opt-in, so "is MCP deployed?" cannot be answered two different ways:

``MCP_ENABLED`` unset or false
    No gateway route is written and the Compose overlay is not layered, so
    ``/k/`` is not a route at all and the web service never sees the switch.
    The deployment serves the HTTP API and the Web application exactly as
    before.  This is the default.

``MCP_ENABLED=true``
    The Compose overlay adds the listener environment to the *existing* web
    service and the gateway gains exactly one location, ``/k/`` → the
    container-internal listener port.  There is no second service, no published
    port, no shadow rate limiter, and no second execution plane: the listener
    is a thread in the canonical web process, so the canonical limiter,
    admission path, and application state are the ones that apply.

The gateway reads its configuration only at container start, so a change is
served after the gateway is restarted; :func:`apply_gateway` reports whether the
route state actually changed so the caller restarts it only then.
"""

from __future__ import annotations

import json
import os
import sys
import urllib.error
import urllib.request

from revocompute_ctl.compose import container_fs, mcp_enabled

#: Server-owned constants.  The upstream is the *service* name and its
#: container-internal port on the compose network, never a host port: nothing
#: outside the stack can reach the listener even while the route exists.
GATEWAY_SNIPPET = "mcp-gateway/mcp.conf"
MCP_PATH = "/k"
MCP_UPSTREAM_PORT = 8081
UPSTREAM_SERVICE = "web"


def gateway_snippet_path(state) -> str:
    return os.path.join(state.server_dir(), *GATEWAY_SNIPPET.split("/"))


def _upstream_port(state) -> int:
    """The container-internal listener port.

    ``MCP_PORT`` comes from the deployment env file (Compose interpolates it into
    the web service), so the controller reads the same value the listener binds
    rather than the controller's own process environment.
    """
    raw = (state.get("MCP_PORT") or "").strip()
    if not raw:
        return MCP_UPSTREAM_PORT
    try:
        return int(raw)
    except ValueError:
        print(f"MCP_PORT must be an integer, got {raw!r}.", file=sys.stderr)
        raise SystemExit(1) from None


def _snippet(*, port: int) -> str:
    # Exactly one location.  The trailing slash makes it a prefix, so only
    # /k/* is proxied and no MCP path can address an operator or admin surface.
    # The proxy settings match the API location's, so the streaming transport
    # gets the same buffering and timeout behavior as the rest of the API rather
    # than a second, invented policy.
    return (
        "# Generated by restart.sh from MCP_ENABLED. Do not edit by hand.\n"
        "# Route ownership is deployment-owned; the nginx template includes this mask.\n"
        f"location {MCP_PATH}/ {{\n"
        f"    proxy_pass http://{UPSTREAM_SERVICE}:{port};\n"
        "    proxy_http_version 1.1;\n"
        '    proxy_set_header Connection "";\n'
        "    proxy_set_header Host $host;\n"
        "    proxy_set_header X-Real-IP $remote_addr;\n"
        "    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;\n"
        "    proxy_set_header X-Forwarded-Proto $origin_proto;\n"
        "}\n"
    )


def _current_snippet(state) -> str | None:
    """The route text already on disk, or ``None`` when it cannot be read.

    An unreadable file is treated as "changed": the write below runs as the
    runner identity, so it can still reconcile a file the invoking host user
    cannot open, and the walk is better off restarting the gateway once than
    leaving two sources of truth.
    """
    try:
        with open(gateway_snippet_path(state), encoding="utf-8") as handle:
            return handle.read()
    except OSError:
        return None


def apply_gateway(state, *, dry_run: bool = False) -> bool:
    """Reconcile the gateway route with ``MCP_ENABLED``; True when it changed."""
    path = gateway_snippet_path(state)
    if not mcp_enabled(state):
        if not os.path.isfile(path):
            return False
        if dry_run:
            print(f"MCP gateway route would be removed: {path}")
            return False
        # SERVER_DIR is the runner identity's directory, so removal goes through
        # the same throwaway-container path the write uses rather than assuming
        # the invoking host user can unlink it.
        container_fs(state, f"rm -f /srv/{GATEWAY_SNIPPET}", [(state.server_dir(), "/srv")])
        print(f"MCP gateway route removed: {path}")
        return True
    port = _upstream_port(state)
    snippet = _snippet(port=port)
    if _current_snippet(state) == snippet:
        # The route already says exactly this.  Rewriting it would be a no-op that
        # still reported a change, and the caller restarts the gateway only when the
        # route state actually changed — so an unchanged route must say so.
        return False
    if dry_run:
        print(f"MCP gateway route would be written: {path} ({MCP_PATH}/ -> {UPSTREAM_SERVICE}:{port})")
        return False
    # The route text carries nginx variables ($host, $remote_addr), so it travels as
    # an argument and is written with a quoted ``printf '%s'`` rather than through a
    # here-doc or stdin, which would expand it. mkdir and the write happen in one
    # program because the mask directory may not exist on a first opt-in.
    container_fs(
        state,
        f"mkdir -p /srv/{os.path.dirname(GATEWAY_SNIPPET)} && printf '%s' \"$0\" > /srv/{GATEWAY_SNIPPET}",
        [(state.server_dir(), "/srv")],
        args=[snippet],
    )
    print(f"MCP gateway route written: {path} ({MCP_PATH}/ -> {UPSTREAM_SERVICE}:{port})")
    return True


def mcp_health(state) -> int:
    """Ask the running web process whether the listener actually answers.

    Reads the deployment capability the web service projects, over the same
    public route a browser uses.  A deployment whose listener is off reports so
    (exit 0); a web service that does not answer, or answers "off" while the env
    file says it should be on, is a real operator problem and is reported as
    failure — never silently as "disabled".
    """
    base = (state.get("SERVER_BASE_URL") or "").rstrip("/")
    if not base:
        print("SERVER_BASE_URL is not set; cannot probe the MCP capability.", file=sys.stderr)
        return 1
    url = f"{base}/compute/api/mcp"
    try:
        with urllib.request.urlopen(url, timeout=10) as response:  # noqa: S310 - operator-configured URL
            payload = json.loads(response.read().decode("utf-8"))
    except (urllib.error.URLError, OSError, ValueError) as exc:
        print(f"The web service did not answer the MCP capability probe at {url}: {exc}", file=sys.stderr)
        return 1
    if payload.get("enabled"):
        print(f"MCP surface enabled at {payload.get('endpoint')} (listener internal port {_upstream_port(state)}).")
        print("Rollback: set MCP_ENABLED=false in the deployment env file, then run `bash run/restart.sh restart`.")
        return 0
    print("MCP surface disabled on this deployment.")
    if mcp_enabled(state):
        print(
            "MCP_ENABLED is set in the env file but the running web process reports the surface as disabled; "
            "restart the deployment so the listener starts.",
            file=sys.stderr,
        )
        return 1
    return 0


def cmd_mcp_status(state) -> int:
    """``mcp-status``: the switch, the route, and what the process reports."""
    path = gateway_snippet_path(state)
    print(f"MCP_ENABLED: {'true' if mcp_enabled(state) else 'false'}")
    print(f"Gateway route: {path} ({'present' if os.path.isfile(path) else 'absent'})")
    print(f"Listener internal port: {_upstream_port(state)} (never published)")
    return mcp_health(state)


