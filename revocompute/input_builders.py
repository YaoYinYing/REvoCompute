"""Input Builder contract: registration, capability binding and envelopes.

An Input Builder is a browser-side scientific editor that produces one or more
declared Task input files.  Core owns the contract that makes that safe: which
builder a Task may use, which logical output binds to which input role, the
bounded authoring envelope the browser submits, and the digest check that binds
the envelope to the accepted immutable bytes.

Builder authoring state is opaque to Core.  A builder's own schema version and
document are carried, bounded and persisted, never interpreted; generated bytes
remain the execution authority.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from typing import Any, Mapping

#: The one envelope version this deployment understands.
ENVELOPE_VERSION = 1
#: Bound on one capability's opaque authoring state.  A native document larger
#: than this is rejected explicitly instead of bloating the Task row.
MAX_STATE_BYTES = 1_048_576
#: Bounded dependency metadata; unresolved bytes are never persisted here.
MAX_DEPENDENCIES = 256
#: The only logical output a current provider exposes.
_LOGICAL_OUTPUT = "input"

_IDENTIFIER = re.compile(r"^[A-Za-z][A-Za-z0-9_-]{0,63}$")
_SHA256 = re.compile(r"^[a-f0-9]{64}$")

#: A target's serialized format, mapped to the Task role formats that accept it.
_FORMAT_ALIASES: dict[str, frozenset[str]] = {
    "json": frozenset({"json"}),
    "yaml": frozenset({"yaml", "yml"}),
    "fasta": frozenset({"fasta", "fa"}),
    "cif": frozenset({"cif", "mmcif"}),
}


class BuilderValidationError(ValueError):
    """One refused builder binding, envelope or output, named by a stable code."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code
        self.message = message


@dataclass(frozen=True, slots=True)
class BuilderDescriptor:
    """One registered builder and the targets it may author.

    ``owner`` is ``None`` for a deployment-owned shared builder and the runner
    family ID for a runner-scoped one.  ``editor_path`` and ``adapter_path`` are
    same-origin application paths, never third-party URLs.
    """

    id: str
    owner: str | None
    api_version: int
    builder_version: int
    state_schema_version: int
    targets: Mapping[str, str]
    adapter: str
    editor_path: str | None = None
    adapter_path: str | None = None

    @property
    def global_id(self) -> str:
        return f"{self.owner}:{self.id}" if self.owner else self.id

    def output_format(self, target: str) -> str | None:
        return self.targets.get(target)

    def accepts_role_format(self, target: str, formats: set[str]) -> bool:
        output = self.targets.get(target)
        return bool(output) and bool(_FORMAT_ALIASES.get(output, frozenset()) & formats)

    @classmethod
    def from_contribution(cls, identifier: str, raw: Mapping[str, Any], *, owner: str) -> "BuilderDescriptor":
        """Validate one runner-owned manifest contribution."""

        api_version = raw.get("api_version", 1)
        if not isinstance(api_version, int) or isinstance(api_version, bool) or api_version < 1:
            raise ValueError(f"Input builder {identifier!r} api_version must be a positive integer")
        builder_version = raw.get("builder_version", 1)
        if not isinstance(builder_version, int) or isinstance(builder_version, bool) or builder_version < 1:
            raise ValueError(f"Input builder {identifier!r} builder_version must be a positive integer")
        state_schema_version = raw.get("state_schema_version", 1)
        if (
            not isinstance(state_schema_version, int)
            or isinstance(state_schema_version, bool)
            or state_schema_version < 1
        ):
            raise ValueError(f"Input builder {identifier!r} state_schema_version must be a positive integer")
        targets = raw.get("targets")
        if not isinstance(targets, Mapping) or not targets:
            raise ValueError(f"Input builder {identifier!r} must declare a targets mapping")
        normalized: dict[str, str] = {}
        for target, output_format in targets.items():
            if not isinstance(target, str) or not _IDENTIFIER.fullmatch(target):
                raise ValueError(f"Input builder {identifier!r} target must be an identifier")
            if not isinstance(output_format, str) or not output_format:
                raise ValueError(f"Input builder {identifier!r} target {target!r} must declare an output format")
            if output_format not in _FORMAT_ALIASES:
                raise ValueError(
                    f"Input builder {identifier!r} target {target!r} format must be one of "
                    f"{sorted(_FORMAT_ALIASES)}"
                )
            normalized[target] = output_format
        adapter = raw.get("adapter", identifier)
        if not isinstance(adapter, str) or not _IDENTIFIER.fullmatch(adapter):
            raise ValueError(f"Input builder {identifier!r} adapter must be an identifier")
        return cls(
            id=identifier,
            owner=owner,
            api_version=api_version,
            builder_version=builder_version,
            state_schema_version=state_schema_version,
            targets=normalized,
            adapter=adapter,
        )


#: Deployment-owned builders.  BioNuTA is the shared scientific workbench; the
#: upstream adapter is served from the exact pinned static tree, so Core stores
#: paths and never code.
SHARED_BUILDERS: dict[str, BuilderDescriptor] = {
    "bionuta": BuilderDescriptor(
        id="bionuta",
        owner=None,
        api_version=1,
        builder_version=2,
        state_schema_version=1,
        targets={
            "alphafold3": "json",
            "opendde": "json",
            "protenix": "json",
            "mol1": "json",
            "openfold3": "json",
            "rosettafold3": "json",
            "chai": "fasta",
            "boltz": "yaml",
            "bioemu2": "yaml",
        },
        adapter="bionuta",
        editor_path="/compute/bionuta/index.html",
        adapter_path="/compute/bionuta/integration/input-builder/index.mjs",
    ),
}


def shared_builder(identifier: str) -> BuilderDescriptor | None:
    return SHARED_BUILDERS.get(identifier)


def resolve_builder(identifier: str, *, owner: str | None, manager: Any | None) -> BuilderDescriptor | None:
    """Resolve a shared builder first, then the runner's own contribution."""

    if ":" in identifier:
        prefix, local = identifier.split(":", 1)
        if prefix == owner and manager is not None:
            return manager.input_builder(local, owner=owner)
        return None
    builder = SHARED_BUILDERS.get(identifier)
    if builder is not None:
        return builder
    return manager.input_builder(identifier, owner=owner) if manager is not None else None


def validate_capability_options(
    options: Mapping[str, Any],
    *,
    builder: BuilderDescriptor | None,
    roles: Mapping[str, Any],
) -> dict[str, Any]:
    """Validate one ``input-builder`` capability's declarative binding.

    Returns the normalized ``{builder, target, outputs}`` mapping.  The caller
    has already resolved the builder for this Task's owner.
    """

    identifier = options.get("builder")
    if not isinstance(identifier, str) or not identifier:
        raise ValueError("Input builder capability must declare a builder ID")
    if builder is None:
        raise ValueError(f"Unknown input builder: {identifier!r}")
    target = options.get("target")
    if not isinstance(target, str) or target not in builder.targets:
        raise ValueError(
            f"Input builder capability target must be one of {sorted(builder.targets)} for {identifier!r}"
        )
    exclusive = options.get("exclusive", False)
    if not isinstance(exclusive, bool):
        raise ValueError("Input builder capability exclusive must be a boolean")
    raw_outputs = options.get("outputs")
    if not isinstance(raw_outputs, Mapping) or not raw_outputs:
        raise ValueError("Input builder capability must map at least one logical output to an input role")
    outputs: dict[str, str] = {}
    for logical, role_name in raw_outputs.items():
        if logical != _LOGICAL_OUTPUT:
            raise ValueError(f"Unsupported input builder logical output: {logical!r}")
        if not isinstance(role_name, str) or role_name not in roles:
            raise ValueError(f"Input builder capability references unknown input role: {role_name!r}")
        role = roles[role_name]
        if not builder.accepts_role_format(target, set(role.formats)):
            raise ValueError(
                f"Input role {role_name!r} does not accept the {target!r} builder output format "
                f"({builder.output_format(target)})"
            )
        outputs[str(logical)] = role_name
    return {"builder": identifier, "target": target, "outputs": outputs, "exclusive": exclusive}


def _bounded_state(value: Any) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise BuilderValidationError("builder_state_invalid", "Builder state must be a JSON object.")
    try:
        encoded = json.dumps(value, separators=(",", ":"), ensure_ascii=True)
    except (TypeError, ValueError) as exc:
        raise BuilderValidationError("builder_state_invalid", "Builder state cannot be serialized.") from exc
    if len(encoded.encode("utf-8")) > MAX_STATE_BYTES:
        raise BuilderValidationError(
            "builder_state_too_large",
            "The builder's native state exceeds the 1 MiB authoring limit; upload the generated file instead.",
        )
    return value


def validate_envelope(
    capability: Any,
    value: Any,
    saved_inputs: list[dict[str, Any]],
) -> None:
    """Check one submitted builder envelope against the accepted input bytes.

    The authored state is opaque; what Core verifies is that the envelope names
    this Task's declared builder and target, that every declared logical output
    binds exactly one accepted file in its declared role with the same name,
    size and SHA-256, and that no extra file was smuggled into a builder-owned
    role.  A client's snapshot is never treated as proof of scientific
    equivalence: the generated bytes are the execution authority.
    """

    if not isinstance(value, dict):
        raise BuilderValidationError("builder_envelope_invalid", "Builder state must be an object.")
    unknown = set(value) - {
        "version",
        "builder",
        "builder_version",
        "state_schema_version",
        "target",
        "revision",
        "state",
        "dependencies",
        "outputs",
    }
    if unknown:
        raise BuilderValidationError(
            "builder_envelope_invalid", f"Builder state has unknown fields: {sorted(unknown)}"
        )
    if value.get("version") != ENVELOPE_VERSION:
        raise BuilderValidationError(
            "builder_envelope_version", "This builder state version is not supported."
        )
    options = getattr(capability, "options", {}) or {}
    expected_builder = options.get("builder")
    expected_target = options.get("target")
    outputs_map = options.get("outputs")
    if not isinstance(outputs_map, dict) or not outputs_map:
        raise BuilderValidationError("builder_binding_invalid", "This builder capability has no output binding.")
    if value.get("builder") != expected_builder or value.get("target") != expected_target:
        raise BuilderValidationError(
            "builder_binding_mismatch",
            "The submitted builder state does not match this capability's declared builder and target.",
        )
    for field in ("builder_version", "state_schema_version", "revision"):
        if not isinstance(value.get(field), int) or isinstance(value.get(field), bool) or value[field] < 0:
            raise BuilderValidationError("builder_envelope_invalid", f"Builder state {field} is invalid.")
    state = _bounded_state(value.get("state"))

    dependencies = value.get("dependencies")
    if not isinstance(dependencies, list) or len(dependencies) > MAX_DEPENDENCIES:
        raise BuilderValidationError("builder_dependencies_invalid", "Builder dependencies must be a bounded list.")
    if dependencies:
        # No current Task declares a role or Runner staging contract for builder
        # dependency bytes.  Refusing is the honest answer; dropping them would
        # silently submit a different system.
        raise BuilderValidationError(
            "builder_dependency_unsupported",
            "This builder input references supporting file dependencies, which no input role in this Task "
            "can stage. Export the generated file and upload it with its dependencies instead.",
        )

    declared = value.get("outputs")
    if not isinstance(declared, list) or len(declared) != len(outputs_map):
        raise BuilderValidationError(
            "builder_output_unbound", "The builder did not bind exactly one output for each declared role."
        )
    by_role: dict[str, list[dict[str, Any]]] = {}
    for item in saved_inputs:
        by_role.setdefault(str(item.get("role")), []).append(item)
    seen_logical: set[str] = set()
    roles_checked: set[str] = set()
    for output in declared:
        if not isinstance(output, dict) or set(output) != {"logical", "role", "name", "size", "sha256"}:
            raise BuilderValidationError("builder_output_invalid", "Builder output binding is malformed.")
        logical = output.get("logical")
        role = output.get("role")
        if logical not in outputs_map or outputs_map[logical] != role:
            raise BuilderValidationError(
                "builder_output_unbound", "A builder output does not match this capability's logical role mapping."
            )
        if logical in seen_logical:
            raise BuilderValidationError("builder_output_invalid", "A builder logical output was bound twice.")
        seen_logical.add(str(logical))
        roles_checked.add(str(role))
        name = output.get("name")
        size = output.get("size")
        digest = output.get("sha256")
        if not isinstance(name, str) or not name or not isinstance(size, int) or isinstance(size, bool) or size < 0:
            raise BuilderValidationError("builder_output_invalid", "Builder output name and size are invalid.")
        if not isinstance(digest, str) or not _SHA256.fullmatch(digest):
            raise BuilderValidationError("builder_output_invalid", "Builder output digest is invalid.")
        candidates = by_role.get(str(role), [])
        if len(candidates) != 1:
            raise BuilderValidationError(
                "builder_output_unbound",
                f"The builder output for role {role!r} must be the only accepted file in that role.",
            )
        accepted = candidates[0]
        if (
            str(accepted.get("original_name") or "") != name
            or int(accepted.get("size", -1)) != size
            or str(accepted.get("hash") or "").lower() != digest
        ):
            raise BuilderValidationError(
                "builder_output_digest_mismatch",
                f"The accepted bytes for role {role!r} do not match the builder's recorded output.",
            )
    if seen_logical != set(outputs_map):
        raise BuilderValidationError("builder_output_unbound", "A declared builder output is missing.")
    if options.get("exclusive") and len(saved_inputs) != len(declared):
        # Some sources are self-contained: the annotated document and the
        # scaffold are alternative start points, not a pair.  The declaration
        # says so, and Core refuses the mixing rather than calling it science.
        raise BuilderValidationError(
            "builder_exclusive_input",
            "This builder produces a self-contained input; remove the other uploaded files before submitting.",
        )
    # A builder-owned role carries only what the envelope bound.  Any other file
    # there came from another capability or a hand-crafted request and must not
    # be submitted under the builder's provenance.
    for role in roles_checked:
        if len(by_role.get(role, [])) != 1:
            raise BuilderValidationError(
                "builder_output_unbound", "A builder-owned role contains an unbound file."
            )
    if not state:
        # An empty object is a valid native state for providers whose document
        # is the bound output itself, so only type/size matter here.
        return


def builder_payload(builder: BuilderDescriptor, *, available: bool) -> dict[str, Any]:
    """Serialize one builder descriptor without inventing availability."""

    return {
        "id": builder.id,
        "owner": builder.owner,
        "api_version": builder.api_version,
        "builder_version": builder.builder_version,
        "state_schema_version": builder.state_schema_version,
        "targets": dict(builder.targets),
        "adapter": builder.adapter,
        "available": available,
        **({"editor_path": builder.editor_path} if builder.editor_path else {}),
        **({"adapter_path": builder.adapter_path} if builder.adapter_path else {}),
    }
